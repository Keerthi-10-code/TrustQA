"""Write the README "Results" section from saved results (no model calls, no hand-typed numbers):
python -m eval.readme_results [--set dev_questions]

Reads eval/results/<set>/summary.json (python -m eval.run_all) and, if present,
eval/results/realworld/summary.md (python -m eval.realworld), and replaces the text between
<!-- RESULTS:START --> and <!-- RESULTS:END --> in README.md.
"""

from __future__ import annotations

import argparse
import json

from eval.questions import ROOT

ROWS = [
    ("accuracy", "Answer accuracy (LLM judge, answerable questions)", True),
    ("answered_rate", "Answered (answerable questions)", True),
    ("verified_precision", "Verified answers that are correct", True),
    ("unsupported_answer_rate", "Shown answers that are wrong", False),
    ("numeric_value", "Numeric answers with the right value", True),
    ("recall@5", "Evidence page in the top 5 passages", True),
    ("mrr", "MRR (first evidence page)", True),
    ("provenance_hit", "Answer cites a labelled evidence page", True),
    ("correct_abstention_rate", "Unanswerable questions refused", True),
    ("over_abstention_rate", "Answerable questions refused", False),
    ("latency_mean_s", "Mean time per answer (s)", False),
]
NAMES = {"A": "A: plain-text RAG", "B": "B: OCR + plain RAG", "C-v0.4": "TrustQA v0.4",
         "C": "**TrustQA (final)**"}


def fmt(v, key):
    if v is None:
        return "n/a"
    return f"{v:.1f}" if key.endswith("_s") else f"{v:.0%}" if key != "mrr" else f"{v:.2f}"


def build(set_name: str) -> str:
    res = ROOT / "eval" / "results" / set_name
    s = json.loads((res / "summary.json").read_text(encoding="utf-8"))
    systems = s["systems"]
    main = [n for n in ("A", "B", "C-v0.4", "C") if n in systems]
    lines = [f"Measured on the {s['questions']}-question development set (`eval/{set_name}.jsonl`: "
             "direct, table, scanned, multi-document and unanswerable questions over the 4 pilot "
             "papers), qwen2.5:3b at temperature 0 for every system, "
             f"{max(systems[n]['repeats'] for n in main)} runs each (mean). "
             "Generated by `python -m eval.readme_results` from `eval/results/`; "
             "plots in `eval/plots/" + set_name + "/`.", "",
             "| | " + " | ".join(NAMES[n] for n in main) + " |",
             "|---|" + "---|" * len(main)]
    m0 = systems[main[-1]]["metrics"]
    counts = {"correct_abstention_rate": m0.get("n_unanswerable"), "over_abstention_rate": m0.get("n_answerable"),
              "accuracy": m0.get("n_answerable"), "answered_rate": m0.get("n_answerable")}
    for key, label, _ in ROWS:
        n = counts.get(key)
        lines.append(f"| {label}{f' (n={round(n)})' if n else ''} | "
                     + " | ".join(fmt(systems[n_]["metrics"].get(key), key) for n_ in main) + " |")
    lines.append("")
    lines.append("Baselines A/B never mark an answer Verified (they have no verification). \"TrustQA "
                 "v0.4\" is the system as tagged after Phase 5; \"final\" adds the Phase 6 fixes "
                 "(section headings, entity-scoped retrieval, document-scope check, quantity-answer "
                 "rule, numeric quote fallback, citation repair, judge retry for skipped claims, "
                 "list-aware prompt, gate as a floor) - see `failures.md`.")
    deltas = s.get("ablation_deltas_vs_C") or {}
    if deltas:
        lines += ["", "**Ablations** (one component removed from the final system; change vs final, "
                  "percentage points):", "",
                  "| removed | accuracy | answered | shown answers wrong | unanswerable refused | evidence in top 5 | cites evidence page |",
                  "|---|---|---|---|---|---|---|"]
        for name, d in deltas.items():
            def pp(k):
                v = d.get(k)
                return "n/a" if v is None else f"{v * 100:+.0f}"
            lines.append(f"| {name.replace('C-no_', '')} | {pp('accuracy')} | {pp('answered_rate')} | "
                         f"{pp('unsupported_answer_rate')} | {pp('correct_abstention_rate')} | "
                         f"{pp('recall@5')} | {pp('provenance_hit')} |")
        lines.append("")
        lines.append("Without the support or the numeric check an answer can never be Verified (by "
                     "design), so Verified-based metrics are not compared for those two.")
    var = systems.get("C", {}).get("variance")
    if var:
        acc = [v for v in var["accuracy"]["values"] if v is not None]
        lines += ["", f"Run-to-run variation of the final system over {len(acc)} runs: accuracy "
                  f"{min(acc):.0%}-{max(acc):.0%}, identical answer and status on "
                  f"{systems['C']['answer_agreement_across_repeats']:.0%} of questions."]
    oq = s.get("ocr_quality") or {}
    for d in oq.get("documents", []):
        lines.append(f"OCR on the scanned pilot paper: character error rate {d['cer_mean']:.1%}, "
                     f"word error rate {d['wer_mean']:.1%} ({len(d['pages'])} pages).")
    ja = s.get("judge_agreement")
    lines.append("")
    lines.append("Answer accuracy is judged by the same 3B model against the reference answers; "
                 + (f"its agreement with a human spot check is {ja['agreement']:.0%} (n={ja['n']})."
                    if ja and ja.get("n") else
                    "it has **not yet been checked against a human** - fill `human_verdict` in "
                    f"`eval/results/{set_name}/spot_check.csv` and run `python -m eval.run_all --report-only`."))
    rw = ROOT / "eval" / "results" / "realworld" / "summary.md"
    if rw.is_file():
        body = rw.read_text(encoding="utf-8").split("\n", 2)[2].strip()
        for code, label in (("| C-v0.4 |", "| TrustQA v0.4 |"), ("| C |", "| **TrustQA (final)** |"),
                            ("| B |", "| B: OCR + plain RAG |")):
            body = body.replace(code, label)
        lines += ["", "**Real-world check** on papers never used during development (DPR and ColBERT, "
                  "an image-only scanned copy of DPR, and both mixed with the pilot papers; "
                  "`python -m eval.realworld`, expected answers taken from the PDFs' text):", "", body,
                  "", "Every answer, citation and warning is in `eval/results/realworld/results.json`; the "
                  "Verified-but-wrong cases are analysed in `phases.md` (Phase 6 notes). Baseline B never "
                  "verifies, so its wrong answers are shown as Partially Supported."]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--set", default="dev_questions")
    args = ap.parse_args(argv)
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    start, end = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
    a, b = text.index(start) + len(start), text.index(end)
    readme.write_text(text[:a] + "\n" + build(args.set) + "\n" + text[b:], encoding="utf-8")
    print("README results updated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
